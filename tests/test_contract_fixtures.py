"""
The contract-v1 fixture pair (issue #42, asked for in Discussion #35).

`tests/fixtures/contract-v1/` holds a synthetic complete export, a partial
one, the planning decision about them and the record of an attempt that
published nothing. They are generated by `scripts/make_contract_fixtures.py`
through the real renderer; these tests regenerate them and fail on any
difference, so the fixtures an importer builds against are what DocsForge
actually writes.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

from docsforge.store import contract
from docsforge.store.contract import parse_revision, validate

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures" / "contract-v1"


def _generator():
    spec = importlib.util.spec_from_file_location(
        "make_contract_fixtures", ROOT / "scripts" / "make_contract_fixtures.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _read(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def test_the_fixtures_are_what_the_code_writes():
    built = _generator().build()
    assert sorted(built) == sorted(p.name for p in FIXTURES.iterdir())
    for name, data in built.items():
        assert _read(name) == data, (
            f"{name} differs from what the renderer writes — run "
            f"`python scripts/make_contract_fixtures.py` and commit the result")


def test_the_fixtures_are_lf_only():
    """A checkout that turned them into CRLF would break every `bytes` and
    `sha256` in them; `.gitattributes` keeps them as written."""
    for path in FIXTURES.iterdir():
        assert b"\r" not in path.read_bytes(), path.name


@pytest.mark.parametrize("name", ["complete.md", "partial.md"])
def test_each_revision_validates(name):
    revision = parse_revision(_read(name).decode("utf-8"))
    assert validate(revision) == []
    jsonschema = pytest.importorskip("jsonschema")
    schema = json.loads((Path(contract.__file__).parent / "contract_v1.schema.json")
                        .read_text(encoding="utf-8"))
    jsonschema.validate(revision.meta, schema)


def test_the_complete_one_is_complete_and_says_how_it_knows():
    meta = parse_revision(_read("complete.md").decode("utf-8")).meta
    assert meta["complete"] is True and meta["complete_reason"] is None
    assert meta["count_basis"] == "sitemap"
    assert meta["stored_pages"] == meta["expected_pages"] == 2
    assert meta["not_stored"]["dead_404"]["count"] == 1, "a 404 is listed, not a gap"


def test_the_partial_one_says_what_is_missing_and_why():
    revision = parse_revision(_read("partial.md").decode("utf-8"))
    meta = revision.meta
    assert meta["complete"] is False
    assert meta["complete_reason"]["code"] == "page-limit"
    assert (meta["stored_pages"], meta["expected_pages"]) == (2, 120)
    assert meta["corpus_role"] == "federated" and meta["store"] == "postgres"
    assert len(revision.pages) == 2


def test_the_decision_points_at_the_two_revisions_and_copies_their_verdicts():
    decision = json.loads(_read("decision.json"))
    revisions = {}
    for name in ("complete.md", "partial.md"):
        meta = parse_revision(_read(name).decode("utf-8")).meta
        revisions[meta["harvest_id"]] = meta
    assert decision["usable_for_planning"] is False
    for judged in decision["judged"]:
        meta = revisions[judged["harvest_id"]]
        assert judged["complete"] is meta["complete"], "copied, never recomputed"
        assert judged["corpus"] == meta["corpus"]
        assert meta["run_id"] == decision["run_id"]


def test_the_decision_has_the_shape_harvests_write():
    from docsforge.tools import forge_tools as ft
    from docsforge.core import federation

    chosen = type("Chosen", (), {"intent": "x"})()
    block = ft._decision_block("acme-sdk", chosen,
                               [federation.Corpus(url="https://a.example/", entry=True)],
                               True, "ok")
    written = json.loads("\n".join(block[2:-1]))
    fixture = json.loads(_read("decision.json"))
    assert list(fixture) == list(written)
    assert list(fixture["judged"][0]) == list(written["judged"][0])


def test_the_stopped_attempt_is_a_record_the_status_check_reads():
    from docsforge.tools import harvest_jobs

    record = json.loads(_read("attempt-stopped.json"))
    job = harvest_jobs._job_from_record(record)
    assert job.state == harvest_jobs.STALLED
    assert job.outcome == "stopped" and job.published == []
    assert record["run_id"].startswith("run-")
